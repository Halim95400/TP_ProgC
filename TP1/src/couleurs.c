#include <stdio.h>

struct Couleur {
    unsigned char R;
    unsigned char G;
    unsigned char B;
    unsigned char A;
};

int main() {
    struct Couleur couleurs[10] = {
        {0xFF, 0x00, 0x00, 0xFF},
        {0x00, 0xFF, 0x00, 0xFF},
        {0x00, 0x00, 0xFF, 0xFF},
        {0xFF, 0xFF, 0x00, 0xFF},
        {0xFF, 0x00, 0xFF, 0xFF},
        {0x00, 0xFF, 0xFF, 0xFF},
        {0xFF, 0xFF, 0xFF, 0xFF},
        {0x00, 0x00, 0x00, 0xFF},
        {0x80, 0x80, 0x80, 0xFF},
        {0xFF, 0xA5, 0x00, 0xFF}
    };

    for (int i = 0; i < 10; i++) {
        printf("Couleur %d : R=%02X G=%02X B=%02X A=%02X\n",
               i + 1,
               couleurs[i].R,
               couleurs[i].G,
               couleurs[i].B,
               couleurs[i].A);
    }

    return 0;
}

