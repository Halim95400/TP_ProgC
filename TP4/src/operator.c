#include "operator.h"

int addition(int a, int b)
{
    return a + b;
}

int soustraction(int a, int b)
{
    return a - b;
}

int multiplication(int a, int b)
{
    return a * b;
}

int division(int a, int b)
{
    return a / b;
}

int modulo(int a, int b)
{
    return a % b;
}

int et_logique(int a, int b)
{
    return a & b;
}

int ou_logique(int a, int b)
{
    return a | b;
}

int negation(int a)
{
    return ~a;
}

